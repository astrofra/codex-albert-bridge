DATA = Path(__file__).parent / "data"
DEFAULTS = json.loads((DATA / "defaults.json").read_text(encoding="utf-8"))
PROFILE_MARKER = "# Generated by codex-albert-bridge."


def codex_home() -> Path:
    return Path(os.environ.get("CODEX_HOME", Path.home() / ".codex")).expanduser().resolve()


def state_home() -> Path:
    return Path(os.environ.get("ALBERT_BRIDGE_HOME", codex_home() / "albert-bridge")).expanduser().resolve()


def validate(settings: dict) -> None:
    if not re.fullmatch(r"[a-zA-Z0-9_./-]+", settings["model"]):
        raise ValueError("Use an exact model ID from the Albert catalog.")
    if not re.fullmatch(r"[a-zA-Z0-9_-]+", settings["profile"]):
        raise ValueError("The profile name must contain only letters, digits, underscores or hyphens.")
    if not 1024 <= settings["port"] <= 65535:
        raise ValueError("The local port must be between 1024 and 65535.")
    window, output, margin = (settings[k] for k in
                              ("context_window", "max_completion_tokens", "headroom_tokens"))
    if min(window, output, margin) <= 0 or window - output - margin < 8192:
        raise ValueError("Context must leave at least 8192 input tokens after output and headroom.")
    url = urlsplit(settings["api_base"])
    if url.scheme != "https" or not url.netloc or url.username or url.password or url.query or url.fragment:
        raise ValueError("The upstream API base must be an HTTPS URL without credentials or query parameters.")


def resolve_codex(value: str | None) -> str:
    candidate = value or shutil.which("codex")
    if not candidate:
        raise ValueError("Codex CLI was not found. Install Codex or pass --codex PATH to configure.")
    p = Path(candidate).expanduser().absolute()
    if p.suffix.lower() in {".cmd", ".bat", ".ps1"}:
        # Avoid cmd.exe and its extra interpretation of user-supplied prompts.
        binaries = list((p.parent / "node_modules" / "@openai").glob("**/codex.exe"))
        if len(binaries) != 1:
            raise ValueError("Pass the native codex.exe path, not a shell wrapper, using --codex.")
        p = binaries[0]
    if not p.is_file():
        raise ValueError("The specified Codex executable does not exist.")
    # Preserve POSIX wrappers and venv paths rather than resolving symlinks.
    return str(p)


