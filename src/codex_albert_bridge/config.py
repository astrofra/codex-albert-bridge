def render_profile(root: Path, settings: dict) -> str:
    q = lambda value: json.dumps(str(value), ensure_ascii=False)
    threshold = settings["context_window"] - settings["max_completion_tokens"] - settings["headroom_tokens"]
    return f'''{PROFILE_MARKER}
model = {q(settings["model"])}
model_provider = "albert_bridge"
model_catalog_json = {q(root / "models.json")}
model_context_window = {settings["context_window"]}
# Reserve output tokens and additional headroom before summarizing history.
model_auto_compact_token_limit = {threshold}
model_auto_compact_token_limit_scope = "total"
model_reasoning_effort = "none"
model_reasoning_summary = "none"
service_tier = "default"
web_search = "disabled"

# Prevent eager loading of large connector schemas and compaction loops.
[apps._default]
enabled = false

[model_providers.albert_bridge]
name = "Albert via local LiteLLM"
base_url = "http://127.0.0.1:{settings["port"]}/v1"
wire_api = "responses"
supports_websockets = false
stream_idle_timeout_ms = 300000
request_max_retries = 2
stream_max_retries = 2

[model_providers.albert_bridge.auth]
command = {q(sys.executable)}
args = ["-m", "codex_albert_bridge", "--state-dir", {q(root)}, "--token"]
timeout_ms = 45000
refresh_interval_ms = 0
'''


def write_configuration(root: Path, settings: dict) -> Path:
    validate(settings)
    home = Path(settings["codex_home"])
    home.mkdir(parents=True, exist_ok=True)
    profile = home / (settings["profile"] + ".config.toml")
    if profile.exists() and not profile.read_text(encoding="utf-8").startswith(PROFILE_MARKER):
        raise ValueError("The selected profile already exists and is not managed by this bridge. Choose --profile NAME.")
    if profile.exists():
        previous = tomllib.loads(profile.read_text(encoding="utf-8"))
        args = previous.get("model_providers", {}).get("albert_bridge", {}).get("auth", {}).get("args", [])
        if str(root) not in args:
            raise ValueError("This profile belongs to another bridge state directory. Choose --profile NAME.")
    files = {
        root / "settings.json": json.dumps(settings, indent=2) + "\n",
        root / "models.json": json.dumps(model_catalog(settings), indent=2) + "\n",
        root / "proxy.yaml": yaml.safe_dump(proxy_config(settings), sort_keys=False),
        profile: render_profile(root, settings),
    }
    for p, text in files.items():
        atomic_write(p, text.encode("utf-8"))
    return profile
